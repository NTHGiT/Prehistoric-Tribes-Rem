#!/usr/bin/env python3
"""Pack decoded levels into the compact files the LOVE game reads.

Reads : assets/maps/level_NN.json (from extract_assets.py), assets/data/a_tables.json
Writes: assets/maps/level_NN.bin   raw tile ids, width*height bytes, row-major
        assets/data/levels.lua     per-level metadata

Level start (chunk 150) and the playable-area limits come straight from the original
loader (f.aN): level 0 only plays inside 40x32, level 5 loses its 32 right-most columns.

usage : python3 tools/pack_levels.py [assets_dir]
"""
import glob, json, os, sys
A = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'assets')
chunks = json.load(open(f'{A}/data/a_tables.json'))['chunks']
start = chunks[150]
rows = []
for p in sorted(glob.glob(f'{A}/maps/level_*.json')):
    m = json.load(open(p)); q, w, h = m['level'], m['width'], m['height']
    data = bytes(t for row in m['tiles'] for t in row); assert len(data) == w * h
    open(f'{A}/maps/level_{q:02d}.bin', 'wb').write(data)
    pw, ph = (40, 32) if q == 0 else ((w - 32, h) if q == 5 else (w, h))
    rows.append('  [%d] = {width = %d, height = %d, playWidth = %d, playHeight = %d, startX = %d, startY = %d, segment = %d},' % (
        q, w, h, pw, ph, start[q * 2], start[q * 2 + 1], m['segment']))
with open(f'{A}/data/levels.lua', 'w') as f:
    f.write('-- GENERATED by tools/pack_levels.py - do not edit.\n-- coordinates are 0-based tile positions\nreturn {\n' + '\n'.join(rows) + '\n}\n')
print('packed', len(rows), 'levels')
